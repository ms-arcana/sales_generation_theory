def build(rec, cell):
    sid = rec["id"][:2]
    stages = rec["sigma"]
    dims_used = []
    for name, mtype, dims in rec["delta"]:
        if name in rec["five_mentions"]:
            dims_used.append((name, dims))
    lines = []
    lines.append(f"あなたは営業資料の作成者。以下の条件で、スライド {len(stages)} 枚の本文を書く。\n")
    lines.append(f"【買い手】{rec['業界']} ／ {rec['セグメント']}")
    lines.append("【読み手と裁定者】")
    for s in rec["seats"]:
        lines.append(f"  ・{s['name']}（見るもの：{'・'.join(s['kappa'])} ／ 通し方：{s['chi']} ／ "
                     f"{'合議' if s['gamma']=='合議' else '単独'} ／ {'資料を読む' if s['reads'] else '資料は読まない'}）")
    if rec["veto"]:
        lines.append(f"  ・{rec['veto'][0]}（決裁権はないが、この人物が拒めば事業は止まる）")
    lines.append(f"  ※ 最後に決めるのは【{rec['seats'][-1]['name']}】であり、この人物は "
                 f"{'・'.join(rec['kappa_n'])} でしか物を見ない。")
    lines.append(f"  ※ 資料を最後まで読む人のうち、最も遠い座席は【{rec['j_star']}】。\n")
    lines.append(SELLER_DESC[cell["seller"]])
    lines.append("")
    lines.append(f"【今日の日付】{TODAY.isoformat()}")
    lines.append("【使える日付（これ以外の日付を『今やる理由』にしてはならない）】")
    for form, d, src, known in rec["tau_ok"]:
        t = next(t for t in cell["nu"].tau if t.form == form and t.d.isoformat() == d)
        kind = {"A": "その日を過ぎると取り返しがつかない終端日", "B": "窓が開き、また閉じる日",
                "C": "終端日から逆算した着手期限", "D": "少しずつ悪くなっていく傾き",
                "Ec": "第三者の承認が下りるまで動かせない解禁日"}[form]
        extra = f"／逃した場合は次まで {t.wait_months} か月待つ" if t.wait_months else ""
        lines.append(f"  ・{d}（{kind}／出所：{src}／買い手にとって{known}{extra}）")
        if t.q:
            rng = f"{t.q_low}〜{t.q_high}" if t.q_low is not None else "（幅は自分で推定して明示）"
            lines.append(f"      添える量：{t.q}  概算 {rng}  出所：{t.q_source}")
            if t.q_recast:
                lines.append(f"      ※ この量は {'・'.join(rec['kappa_n'])} では直接読めない。"
                             f"同じ枚の中で、誰の何が {'・'.join(rec['kappa_n'])} の側で動くのかを書き添えること。")
    lines.append("")
    lines.append("【⑤で扱う打ち手（これ以外は⑤に出さない）】")
    for name, dims in dims_used:
        lines.append(f"  ・「{name}」 → " + " ／ ".join(DIM_PLAIN[d] for d in dims if d in DIM_PLAIN))
    if rec["d7_basis"]:
        lines.append("【⑥で、同種の他社ではなく自社が残る根拠として使えるもの】")
        lines.append("  ・" + " ／ ".join(DIM_PLAIN.get(d, d) for d in rec["d7_basis"]))
    elif "B_intra_category" in rec["blocks"]:
        lines.append("【⑥】同種の他社が残る中で自社が残る根拠を書くこと（使える材料は上の保有物から選ぶ）")
    lines.append("")
    lines.append("【必ず入れる要素】")
    for b in rec["blocks"]:
        lines.append(f"  ・{BLOCK_PLAIN[b]}")
    lines.append("【書き方の制約】")
    for r in rec["rules"]:
        k = r.split(":")[0]
        if k in RULE_PLAIN:
            lines.append(f"  ・{RULE_PLAIN[k]}")
    lines.append("")
    lines.append(f"【作る枚】{'・'.join(stages)}（この段だけ。他の段は作らない）")
    for s in stages:
        spec = STAGE_SPEC[s]
        if s == "⑥" and "②" not in stages:
            spec = spec.replace("②で導入した単位をそのまま使い、元の単位へ比例換算して戻さない。",
                                "④で使った単位をそのまま使い、別の単位へ比例換算して戻さない。")
        lines.append(f"  {s}：{spec}")
    lines.append("")
    lines.append("【本文に出してはならない語】" + "、".join(BAN))
    lines.append("  これらは資料を設計するための言葉であって、買い手に見せる言葉ではない。"
                 "現場の言葉に置き換えて書くこと。")
    lines.append("")
    lines.append("【出力】各枚 200〜400字の日本語本文。見出し語だけの箇条書きにしない。"
                 "そのままスライドに貼れる文章にすること。"
                 "加えて、自分の書いたものについて declared の各項目を正直に申告し、"
                 "prediction では各段について買い手がどう反応するかを "
                 "通過／揺らぐ／棄却 で予測し、最も長く止まる段を一つ挙げること。")
    return "\n".join(lines)


def main():
    out = []
    for rec, cell in zip(DEC, CELLS):
        assert rec["id"] == cell["id"]
        out.append({"id": rec["id"], "sigma": rec["sigma"],
                    "persona": PERSONA[rec["id"][:2]],
                    "prompt": build(rec, cell)})
    json.dump(out, open("prompts8_v2.json", "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print(f"{len(out)} prompts / avg {sum(len(o['prompt']) for o in out)//len(out)} chars")
    print(out[6]["prompt"][:1500])


if __name__ == "__main__":
    main()
