EDITS = {
    "E1-P1": {"good": [(E1_PAY, E1_PAY_G), (E1_SEATS, E1_SEATS_G), (E1_HOURS, E1_HOURS_G)],
              "bad":  [(E1_SEATS, E1_SEATS_B)]},
    "R2-P2": {"good": [(R2_PAY, R2_PAY_G), (R2_SEATS, R2_SEATS_G), (R2_CASE, R2_CASE_G)],
              "bad":  [(R2_SEATS, R2_SEATS_B)]},
}


def body_of(cid, ver):
    r = V[cid]; sigma = DEC[cid]["sigma"]
    copy = dict(r["copy"])
    if ver != "現行":
        s6 = copy["⑥"]
        for a, b in EDITS[cid]["good" if ver == "改善" else "bad"]:
            assert a in s6, f"{cid}/{ver}: 置換元が無い ―― {a[:40]}"
            s6 = s6.replace(a, b, 1)
        copy["⑥"] = s6
    return "\n\n".join(f"── {s} 枚目 ──\n{copy.get(s,'')}" for s in sigma), copy["⑥"]


def main():
    d = pathlib.Path("r1"); d.mkdir(exist_ok=True)
    n = 0
    print(f"{'セル':8s}{'版':6s}{'⑥字数':>7s}  差分")
    for cid in ("E1-P1", "R2-P2"):
        base = V[cid]["copy"]["⑥"]
        for ver in ("劣化", "改善"):
            body, s6 = body_of(cid, ver)
            print(f"{cid:8s}{ver:6s}{len(s6):>7d}  {len(s6)-len(base):+d}字")
            for seat, _k, _f, _o in DEC[cid]["chain"]:
                dump_stamped({"id": cid, "seat": seat, "version": ver,
                              "sigma": DEC[cid]["sigma"],
                              "persona": PER[(cid, seat)], "body": body},
                             str(d / f"in_buyer_{cid}__{ver}__{seat}.json"))
                n += 1
    print(f"\n買い手 {n} 体（2セル × 2版 × 2座席）。現行は第13版の実測を対照に使う。")
    # ①〜⑤ が一字も変わっていないことを確認する
    for cid in ("E1-P1", "R2-P2"):
        for ver in ("劣化", "改善"):
            b, _ = body_of(cid, ver)
            base = "\n\n".join(f"── {s} 枚目 ──\n{V[cid]['copy'].get(s,'')}"
                               for s in DEC[cid]["sigma"])
            pre_b = b.split("── ⑥ 枚目 ──")[0]
            pre_a = base.split("── ⑥ 枚目 ──")[0]
            assert pre_b == pre_a, f"{cid}/{ver}: ⑥以外が変わっている"
    print("①〜⑤ は一字も変わっていない（確認済み）")


if __name__ == "__main__":
    main()
