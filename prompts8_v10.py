# A25c で照合側は正規化したが、**指示の側は直っていなかった**。鉤括弧で割り、個数を明示する。

def kn_show(kn) -> str:
    """κ_n を、一語に見えない形で並べる（文中に埋める位置で使う）"""
    kn = list(kn)
    return "".join(f"「{k}」" for k in kn) if kn else "（未登録）"


def kn_all(kn) -> str:
    """κ_n を並べ、**個数を明示する**（③・A23 と同じ形。単数なら個数は付けない）"""
    kn = list(kn)
    if len(kn) <= 1:
        return kn_show(kn)
    return kn_show(kn) + f" の{len(kn)}つ**すべて**"

